"""
Render a stored analysis as a self-contained Markdown report (pure Python).

Input is the AnalysisDetailSerializer output, so the report always matches
what the API and UI show. Markdown is portable: readable as plain text, renders
on GitHub, and converts to PDF/Word with common tools.
"""
from typing import Any

STATUS_LABELS = {"matched": "Matched", "missing": "Missing", "related": "Related skill found"}


def _md(text: Any) -> str:
    """Escape characters that would break Markdown tables or formatting."""
    value = str(text if text is not None else "")
    for ch in ("\\", "|", "*", "_", "`", "<", ">", "#"):
        value = value.replace(ch, "\\" + ch)
    return " ".join(value.split())


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{float(value):.1f}%"


def _section(lines: list[str], title: str, items: list[str], empty: str) -> None:
    lines += ["", f"## {title}", ""]
    lines += [f"- {_md(i)}" for i in items] if items else [f"_{empty}_"]


def render_markdown(data: dict) -> str:
    breakdown = data.get("breakdown", {})
    req = breakdown.get("required", {})
    pref = breakdown.get("preferred", {})
    lines = [
        f"# Resume analysis: {_md(data['job_title'])}",
        "",
        f"- **Resume:** {_md(data['resume_title'])}",
        f"- **Analysed:** {_md(data['created_at'])}",
        f"- **Algorithm:** {_md(data['algorithm_version'])}",
        "",
        f"## Matching score: {float(data['score']):.1f} / 100",
        "",
        f"> {_md(data.get('score_label', ''))}",
        "",
        f"- Formula: {_md(breakdown.get('formula', ''))}",
        f"- Required skills: {_pct(data.get('required_coverage'))} "
        f"({req.get('matched_weight', 0)}/{req.get('total_weight', 0)} weight)",
        f"- Preferred skills: {_pct(data.get('preferred_coverage'))} "
        f"({pref.get('matched_weight', 0)}/{pref.get('total_weight', 0)} weight)",
        "- Related skills are shown for context and do not count toward the score.",
        "",
        "## Skill results",
        "",
        "| Skill | Kind | Weight | Result | Why |",
        "|---|---|---|---|---|",
    ]
    for r in data.get("skill_results", []):
        lines.append(
            f"| {_md(r['skill_name'])} | {_md(r['kind'])} | {r['weight']} | "
            f"{STATUS_LABELS.get(r['status'], _md(r['status']))} | {_md(r['explanation'])} |"
        )
    evidence_lines = []
    for r in data.get("skill_results", []):
        for e in r.get("evidence", []):
            evidence_lines.append(f"- **{_md(r['skill_name'])}**: {_md(e['location'])}: “{_md(e['text'])}”")
    _section(lines, "Strengths", data.get("strengths", []), "None identified.")
    _section(lines, "Areas for improvement", data.get("improvements", []), "None identified.")
    _section(lines, "Suggestions", data.get("suggestions", []), "None.")
    lines += ["", "## Evidence from the resume", ""]
    lines += evidence_lines or ["_No evidence lines recorded._"]
    lines += [
        "",
        "---",
        "_Generated by CareerForge. The score measures skill overlap between this resume and the job "
        "description; it is not a prediction of hiring outcomes._",
        "",
    ]
    return "\n".join(lines)
